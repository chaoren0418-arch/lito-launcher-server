function Assert-DatabaseIdentifier([string]$Value) {
    if ($Value -notmatch '^[A-Za-z0-9_]+$') {
        throw "Invalid database identifier: $Value"
    }
}

function Assert-Source([string]$Path, [string]$ExpectedHash) {
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        throw "SQL source is missing: $Path"
    }
    $actual = (Get-FileHash -Algorithm SHA256 -LiteralPath $Path).Hash
    if ($actual -ne $ExpectedHash) {
        throw "SQL source hash mismatch: $Path actual=$actual expected=$ExpectedHash"
    }
}

